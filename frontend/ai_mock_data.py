
def get_ai_response(user_message, image_path=None):

    message = user_message.lower()

    if image_path:
        return (
            "Я отримала фотографію твого акваріума! 🐠\n\n"
            "На основі зображення можу допомогти оцінити "
            "загальний вигляд акваріума.\n\n"
            "Зверни увагу на прозорість води, стан рослин "
            "та активність рибок.\n\n"
            "Для точного визначення параметрів води "
            "потрібні спеціальні тести."
        )

    if "риб" in message:
        return (
            "З радістю допоможу з рибками! 🐟\n\n"
            "Розкажи, будь ласка, що саме тебе турбує: "
            "поведінка, апетит чи зовнішній вигляд?"
        )

    elif "вод" in message:
        return (
            "Я допоможу оцінити стан води! 💧\n\n"
            "Напиши показники pH, температури та "
            "інші результати тестів, якщо вони є."
        )

    elif "рослин" in message:
        return (
            "Давай перевіримо стан рослин! 🌿\n\n"
            "Опиши, що саме змінилося: колір листя, "
            "поява плям чи уповільнення росту."
        )

    elif "привіт" in message:
        return (
            "Привіт! 💙\n\n"
            "Я твій AI-помічник Smart Aquarium Assistant. "
            "Допоможу з доглядом за акваріумом!"
        )

    else:
        return (
            "Цікаве запитання! 🐠\n\n"
            "Я твій помічник з догляду за акваріумом. "
            "Розкажи трохи більше, щоб я могла допомогти."
        )
